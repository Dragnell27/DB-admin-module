package modules

import "testing"

// HasFillStrategies distingue una acción con estrategias de una clásica.
func TestHasFillStrategies(t *testing.T) {
	withStrat := Action{InputFields: []FieldSpec{
		{Name: "x", Source: FieldSourceInput},
		{Name: "valor_lista", Source: FieldSourceFillStrategy, Strategy: &FillStrategy{Kind: StrategyCaptureFromCatalog}},
	}}
	if !HasFillStrategies(withStrat) {
		t.Fatalf("una acción con un campo fillStrategy debe dar true")
	}
	classic := Action{InputFields: []FieldSpec{{Name: "x", Source: FieldSourceInput}}}
	if HasFillStrategies(classic) {
		t.Fatalf("una acción sin estrategias debe dar false")
	}
}

// CreateFieldSpecs devuelve solo las capturas (capture-from-catalog) y conserva
// los campos no-fillStrategy; omite derive-*/constant/autogenerated.
func TestCreateFieldSpecs_OnlyCaptures(t *testing.T) {
	act := Action{InputFields: []FieldSpec{
		{Name: "__capture_comercio", Required: true, Source: FieldSourceFillStrategy, Strategy: &FillStrategy{Kind: StrategyCaptureFromCatalog}},
		{Name: "valor_lista", Required: true, Source: FieldSourceFillStrategy, Strategy: &FillStrategy{Kind: StrategyCaptureFromCatalog}},
		{Name: "list_numero_h", Source: FieldSourceFillStrategy, Strategy: &FillStrategy{Kind: StrategyDeriveFromOption}},
		{Name: "padr_numero", Source: FieldSourceFillStrategy, Strategy: &FillStrategy{Kind: StrategyDeriveViaFK}},
		{Name: "otro", Source: FieldSourceInput},
	}}
	got := CreateFieldSpecs(act)
	names := map[string]bool{}
	for _, f := range got {
		names[f.Name] = true
	}
	if !names["__capture_comercio"] || !names["valor_lista"] {
		t.Fatalf("deben conservarse las capturas: %+v", names)
	}
	if !names["otro"] {
		t.Fatalf("deben conservarse los campos no-fillStrategy: %+v", names)
	}
	if names["list_numero_h"] || names["padr_numero"] {
		t.Fatalf("las derivaciones no deben validarse contra el input: %+v", names)
	}
	// Required se conserva en las capturas.
	for _, f := range got {
		if f.Name == "valor_lista" && !f.Required {
			t.Fatalf("CreateFieldSpecs debe conservar Required de la captura")
		}
	}
}
